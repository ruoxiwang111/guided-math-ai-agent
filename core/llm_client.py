def _definition_only_text(spec, details) -> str:
    """The learner wrote a sensible '设……' but no equation yet: acknowledge it, point to the next step."""
    vd = (spec.get("learner_definition") or "").strip()
    head = f"“{vd}”这个设法可以" if vd else "这个设法可以"
    if details.get("defines_relation"):
        head += "，另一个量也已经用 x 表示出来了"
    return head + "。下一步：找一找题目里哪两个量是相等的，用 x 把它们写成一个方程。"


def _answer_part_text(rule, details):
    """Wording for final-answer checks that name the exact part (details from diagnosis)."""
    right, wrong = details.get("right", []), details.get("wrong", [])
    if rule == "answer_part_wrong":
        head = f"{'、'.join(right)}的答案对了！" if right else ""
        return (f"{head}{'、'.join(wrong)}再核对一下：你解出的 x 表示哪个量？"
                f"{'、'.join(wrong)}要怎样由 x 算出来？")
    if rule == "answer_unit_missing":
        return f"数都对了！{'、'.join(details.get('unit_missing', []))}后面还少了单位，补上再提交。"
    if rule == "answer_incomplete":
        head = f"{'、'.join(right)}写对了！" if right else ""
        return f"{head}再看一眼题目最后问的是什么：还要写出{'、'.join(details.get('missing', []))}，把它也补上。"
    return None

