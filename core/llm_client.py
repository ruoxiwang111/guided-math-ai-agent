VERIFY_RE = re.compile(r"检查|检验|验算|验证|代入|代回|带回")


def _answer_fallback(spec: dict) -> str:
    """Deterministic answer when no LLM is available (or its answer leaked)."""
    q = spec.get("learner_question", "")
    conditions = spec.get("verification_conditions") or []
    if VERIFY_RE.search(q) or spec.get("reflection_kind") == "prompt_verification":
        items = "；".join(f"{'①②③④⑤'[i]} {c}" for i, c in enumerate(conditions[:5]))
        known = "" if spec.get("must_not_contain") else f"把你的答案（{spec.get('final_answer_text')}）"
        return (f"“代回原题检查”就是{known or '把你求出的结果'}放回题目里，逐条看题目的条件是否都成立。"
                f"这道题可以检查：{items}。都成立，答案就可靠了。")
    task = ASK_TEXT.get(spec.get("current_task"), "")
    return f"好问题！结合题目想一想：{task} 先按你的理解写出来提交，我会根据你写的内容给你具体提示。".strip()


