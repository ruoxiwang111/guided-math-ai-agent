NUM_RE = re.compile(r"(?<![\d.])\d+(?:\.\d+)?(?:/\d+)?(?![\d.])")
EQ_CANDIDATE_RE = re.compile(r"[0-9xX（）()+\-−*×÷/.\s＋－＝=]+")


LINE_REF_RE = re.compile(r"第\s*\d+\s*(行|步|个)")


def _numbers(text):
    text = LINE_REF_RE.sub("", text or "")              # "第2行" is a line number, not a value
    return {mc.nsimplify(mc.S(n), rational=True) for n in NUM_RE.findall(text)}


def _learner_equations(spec: dict) -> list[str]:
    li = spec.get("learner_input") or {}
    lines = []
    if li.get("equation"):
        lines.append(li["equation"])
    steps = li.get("steps")
    lines += steps.splitlines() if isinstance(steps, str) else list(steps or [])
    lines += [ln for h in spec.get("learner_history") or [] for ln in str(h).splitlines()]
    out = []
    for ln in lines:
        nl = normalize_line(ln)
        if nl.ok and nl.kind == "equation":
            out.append(nl.normalized)
    return out


def _squash_text(t: str) -> str:
    return re.sub(r"[\s()（）*×·，,。“”\"'：:；;？?！!]", "", t or "")


def check_leakage(text: str, spec: dict) -> list[str]:
    """
    Violations of spec["must_not_contain"] that can be detected automatically:
      final_answer       the reference answer value appears, and it is not a number
                         already given in the question text
      complete_equation  an equation in the text is equivalent to the reference equation
    ('key_intermediate_value' cannot be detected reliably; it is left to manual review.)
    """
    forbidden = set(spec.get("must_not_contain", []))
    violations = []
    if "final_answer" in forbidden:
        answer = mc.nsimplify(mc.S(spec["reference_answer"]), rational=True)
        # numbers the learner already wrote themselves are not leaked by quoting them back
        learner_text = json.dumps([spec.get("learner_input") or {}, spec.get("learner_history") or []],
                                  ensure_ascii=False)
        given = _numbers(spec.get("question", "")) | _numbers(learner_text)
        if answer in _numbers(text) and answer not in given:
            violations.append("final_answer")
    if "reference_model" in forbidden or "s1_target" in forbidden:
        said = _squash_text(text)
        mine = _squash_text(" ".join(spec.get("learner_history") or []) + json.dumps(
            spec.get("learner_input") or {}, ensure_ascii=False))
        if "reference_model" in forbidden and any(e and e in said and e not in mine
                                                  for e in (_squash_text(x) for x in spec.get("reference_expressions") or [])):
            violations.append("reference_model")
        target = _squash_text(spec.get("target") or "")
        if "s1_target" in forbidden and len(target) >= 4 and target in said:
            violations.append("s1_target")
    if "complete_equation" in forbidden:
        own = _learner_equations(spec)
        for cand in EQ_CANDIDATE_RE.findall(text or ""):
            if "=" in cand or "＝" in cand:
                line = normalize_line(cand.strip())
                if line.ok and mc.equivalent(line.normalized, spec["reference_equation"]):
                    if any(mc.equivalent(line.normalized, o) for o in own):
                        continue                         # quoting the learner's own line is not leakage
                    violations.append("complete_equation")
                    break
    return violations


