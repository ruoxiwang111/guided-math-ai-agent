def _load_dotenv(path: Path):
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$", line)
        if m and m.group(1) not in os.environ:
            os.environ[m.group(1)] = m.group(2).strip().strip('"').strip("'")


class LLMError(RuntimeError):
    pass


class DeepSeekBackend:
    """Minimal OpenAI-compatible chat client (no extra dependency)."""

    def __init__(self, api_key: str | None = None, model: str = "deepseek-chat",
                 base_url: str = "https://api.deepseek.com", temperature: float = 0.3, timeout: int = 30):
        _load_dotenv(Path(__file__).resolve().parents[1] / ".env")
        self.api_key = api_key or os.environ.get("DEEPSEEK_API_KEY")
        if not self.api_key:
            raise LLMError("DEEPSEEK_API_KEY not set (environment or .env)")
        self.model, self.base_url, self.temperature, self.timeout = model, base_url.rstrip("/"), temperature, timeout

    def complete(self, system: str, user: str) -> str:
        body = json.dumps({
            "model": self.model, "temperature": self.temperature,
            "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
            "response_format": {"type": "json_object"},
        }).encode("utf-8")
        req = urllib.request.Request(f"{self.base_url}/chat/completions", data=body, method="POST",
                                     headers={"Content-Type": "application/json",
                                              "Authorization": f"Bearer {self.api_key}"})
        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as r:
                data = json.loads(r.read().decode("utf-8"))
            return data["choices"][0]["message"]["content"]
        except (urllib.error.URLError, KeyError, json.JSONDecodeError, TimeoutError) as exc:
            raise LLMError(f"DeepSeek call failed: {exc}") from exc

    def describe(self):
        return {"backend": "deepseek", "model": self.model, "temperature": self.temperature}


def default_backend():
    """DeepSeek if a key is available, else None (template-only)."""
    try:
        return DeepSeekBackend()
    except LLMError:
        return None


