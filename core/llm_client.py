def _answer_part_text(rule, details):
    """Wording for final-answer checks that name the exact part (details from diagnosis)."""
    right, wrong = details.get("right", []), details.get("wrong", [])
    if rule == "answer_part_wrong":
        head = f"{'、'.join(right)}的答案对了！" if right else ""
        return (f"{head}{'、'.join(wrong)}再核对一下：你解出的 x 表示哪个量？"
                f"{'、'.join(wrong)}要怎样由 x 算出来？")
    if rule == "answer_unit_missing":
        return f"数都对了！{'、'.join(details.get('unit_missing', []))}后面还少了单位，补上再提交。"
    if rule == "answer_incomplete":
        return f"题目还要求写出{'、'.join(details.get('missing', []))}，把它也补上。"
    return None

