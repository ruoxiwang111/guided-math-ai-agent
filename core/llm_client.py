def cache_key(question_id, state, category, subtype, level) -> str:
    return f"{question_id}|{state}|{category or 'none'}|{subtype or '-'}|L{level}"


def load_hint_cache(path: str | Path = DEFAULT_CACHE, require_approved: bool = False) -> dict:
    """{key: text}. Rejected entries are never used; pending ones only if require_approved is False."""
    path = Path(path)
    if not path.exists():
        return {}
    entries = json.loads(path.read_text(encoding="utf-8")).get("entries", {})
    ok = {"approved"} if require_approved else {"approved", "pending"}
    return {k: e["text"] for k, e in entries.items() if e.get("review_status", "pending") in ok}


def fill_slots(text: str, spec: dict) -> str | None:
    """Fill {slot}s from the learner context; None if a slot is unknown or has no value."""
    values = {
        "learner_line": spec.get("learner_line"), "prev_line": spec.get("prev_line"),
        "line_no": spec.get("line_no"), "learner_equation": spec.get("learner_equation"),
        "learner_definition": spec.get("learner_definition"),
        "acknowledge": _ack_prefix(spec).rstrip("。") or None,
    }
    out = text
    for name in set(SLOT_RE.findall(text)):
        if name == "acknowledge" and not values["acknowledge"]:
            out = out.replace("{acknowledge}", "")           # nothing to acknowledge: drop it
            continue
        if name not in values or values[name] in (None, ""):
            return None
        out = out.replace("{" + name + "}", str(values[name]))
    return out.lstrip("。，,. ").strip()


def default_mode() -> str:
    m = os.environ.get("WORDING_MODE", CACHED).lower()
    return m if m in WORDING_MODES else CACHED


class TutorVoice:
    """
    Renders TutorActions.

    mode (default: env WORDING_MODE, else "cached")
      template  fixed templates only (offline, tests)
      cached    reviewed slot-templates from data/hint_cache.json, filled with the learner's
                own text; on a cache miss → live (if a backend exists) → template
      live      the LLM words every hint in real time → template on failure
    Every text that is shown passes the leakage check first.
    """

    def __init__(self, backend=None, question: dict | None = None, mode: str | None = None,
                 cache: dict | None = None):
        self.backend = backend
        self.q = question or {}
        self.mode = mode or default_mode()
        if self.mode == CACHED and cache is None:
            cache = load_hint_cache()
        self.cache = cache or {}

    def _spec(self, action):
        spec = dict(action.prompt_spec)
        spec.setdefault("category", action.category)
        spec.setdefault("relationship", self.q.get("relationship"))
        spec.setdefault("final_answer_text", self.q.get("final_answer_text"))
        return spec

    def render(self, action) -> Message:
        t = action.type
        spec = self._spec(action)
        if t == ASK:
            return Message(ASK_TEXT.get(action.task, "请继续。"), "template", t)
        if t == EVIDENCE_REQUEST:
            d = action.diagnosis or {}
            rule = d.get("rule")
            text = (_answer_part_text(rule, d.get("details") or {})
                    or EVIDENCE_TEXT_BY_RULE.get(rule) or EVIDENCE_TEXT.get(action.request))
            if text is None:                       # notation clarification from the normaliser
                d = action.diagnosis or {}
                text = d.get("evidence", "").split("：", 1)[-1] or "这个写法有歧义，请用括号写清楚。"
            if action.request == "ask_discriminating_question":
                # no error category can be claimed: ask about THIS equation, never name an error
                return self._llm_or(text, DISCRIMINATE_SYSTEM_PROMPT, _discriminate_user_prompt(spec, text), spec, t)
            return Message(text, "template", t)
        if t == METACOGNITIVE:
            template = METACOGNITIVE_TEXT.get(action.task, "你是怎么确定这一步是对的？")
            return self._llm_or(template, META_SYSTEM_PROMPT, _meta_user_prompt(spec, template), spec, t)
        if t == REVEAL:
            return Message(_reveal_text(spec, action.state), "template", t, hint_level=4, category=action.category)
        if t == COMPLETE:
            return Message(DONE_TEXT, "template", t)
        if t == UNEXPECTED_INPUT:
            return Message(ASK_TEXT.get(action.task, "请按提示作答。"), "template", t)
        if t == HINT:
            return self._render_hint(action, spec)
        if t == ANSWER_QUESTION:
            return self._render_answer(action, spec)
        return Message("请继续。", "template", t)

    def _llm_or(self, template, system, user, spec, action_type) -> Message:
        """LLM wording in live/cached mode, leakage-checked, else the template."""
        if self.mode == TEMPLATE or self.backend is None:
            return Message(template, "template", action_type)
        attempts = []
        for _ in range(2):
            try:
                text = json.loads(self.backend.complete(system, user))["message"].strip()
            except (LLMError, json.JSONDecodeError, KeyError, TypeError) as exc:
                attempts.append({"error": str(exc)})
                break
            violations = check_leakage(text, spec)
            if text and not violations:
                return Message(text, "llm", action_type, attempts=attempts)
            attempts.append({"text": text, "violations": violations})
        return Message(template, "template_fallback", action_type, attempts=attempts)

    # -- learner's own questions ----------------------------------------------------
    def _render_answer(self, action, spec) -> Message:
        fallback = _answer_fallback(spec)
        if self.backend is None:
            return Message(fallback, "template", ANSWER_QUESTION, spec.get("hint_level"),
                           leakage_violations=check_leakage(fallback, spec))
        attempts = []
        for _ in range(2):
            try:
                raw = self.backend.complete(CHAT_SYSTEM_PROMPT, _chat_user_prompt(spec))
                text = json.loads(raw)["message"].strip()
            except (LLMError, json.JSONDecodeError, KeyError, TypeError) as exc:
                attempts.append({"error": str(exc)})
                break
            violations = check_leakage(text, spec)
            if text and not violations:
                return Message(text, "llm", ANSWER_QUESTION, spec.get("hint_level"), attempts=attempts)
            attempts.append({"text": text, "violations": violations})
        return Message(fallback, "template_fallback", ANSWER_QUESTION, spec.get("hint_level"),
                       leakage_violations=check_leakage(fallback, spec), attempts=attempts)

    def _render_hint(self, action, spec) -> Message:
        level, cat = action.hint_level or 1, action.category
        template = _template_hint(cat, level, spec) if level <= 3 else _level4_fallback(cat, spec)

        if self.mode == CACHED:
            key = cache_key(self.q.get("question_id"), action.state, cat, action.error_subtype, level)
            cached = self.cache.get(key)
            text = fill_slots(cached, spec) if cached else None
            if text and not check_leakage(text, spec):
                return Message(text, "cache", HINT, level, cat, [])

        if self.mode == TEMPLATE or self.backend is None:
            return Message(template, "template", HINT, level, cat, check_leakage(template, spec))

        attempts = []
        for _ in range(2):                                       # one retry
            try:
                raw = self.backend.complete(SYSTEM_PROMPT, _hint_user_prompt(spec, template))
                text = json.loads(raw)["message"].strip()
            except (LLMError, json.JSONDecodeError, KeyError, TypeError) as exc:
                attempts.append({"error": str(exc)})
                break
            violations = check_leakage(text, spec)
            if not violations and text:
                return Message(text, "llm", HINT, level, cat, [], attempts)
            attempts.append({"text": text, "violations": violations})
        return Message(template, "template_fallback", HINT, level, cat, check_leakage(template, spec), attempts)

    # -- S1 free text -----------------------------------------------------------------
    def classify_s1(self, question_text: str, target: str, learner_text: str) -> bool | None:
        """True / False if the LLM can decide, None if unclear or no backend (use the choice item)."""
        if self.backend is None or not learner_text.strip():
            return None
        system = ("判断学生对“这道题最后要求我们求什么？”的回答，是否指向题目真正要求的量。"
                  "只看目标量是否一致，不评价表达。只输出 JSON："
                  '{"matches_target": true} 或 {"matches_target": false} 或 {"matches_target": "unclear"}')
        user = json.dumps({"题目": question_text, "题目要求的量": target, "学生回答": learner_text}, ensure_ascii=False)
        try:
            v = json.loads(self.backend.complete(system, user)).get("matches_target")
        except (LLMError, json.JSONDecodeError, AttributeError):
            return None
        return v if isinstance(v, bool) else None


